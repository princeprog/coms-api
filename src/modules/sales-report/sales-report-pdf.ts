import { join } from 'node:path';
import { readFileSync } from 'node:fs';
import PDFDocument from 'pdfkit';
import {
  change,
  comparisonLabel,
  count,
  longDate,
  manilaDateTime,
  percent,
  periodLabel,
  peso,
  serviceLabel,
  shortDate,
} from './sales-report-format';
import type { SalesReport } from './sales-report.service';

const REGULAR_FONT = join(
  __dirname,
  '..',
  '..',
  'assets',
  'fonts',
  'NotoSans-Regular.ttf',
);
const BOLD_FONT = join(
  __dirname,
  '..',
  '..',
  'assets',
  'fonts',
  'NotoSans-Bold.ttf',
);
const LOGO = join(
  __dirname,
  '..',
  '..',
  'assets',
  'emmas-chicken-house-logo.png',
);
const MARGIN = 40;
const INK = '#111827';
const MUTED = '#6B7280';
const LINE = '#E5E7EB';
const GOOD = '#047857';
const BAD = '#B91C1C';

type Column = { header: string; width: number; align?: 'left' | 'right' };

/** Renders the owner's sales report as an A4 PDF. */
export function renderSalesReportPdf(
  report: SalesReport,
  meta: { generatedBy: string; generatedAt: Date },
): Promise<Buffer> {
  const doc = new PDFDocument({
    // Avoid PDFKit's dynamically loaded Helvetica module in serverless bundles.
    font: REGULAR_FONT,
    size: 'A4',
    margin: MARGIN,
    bufferPages: true,
    info: { Title: `Sales report – ${periodLabel(report)}`, Author: 'COMS' },
  });
  // Explicit reads also make these assets discoverable by deployment file tracing.
  doc.registerFont('regular', readFileSync(REGULAR_FONT));
  doc.registerFont('bold', readFileSync(BOLD_FONT));
  const chunks: Buffer[] = [];
  doc.on('data', (chunk: Buffer) => chunks.push(chunk));
  const done = new Promise<Buffer>((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const width = doc.page.width - MARGIN * 2;
  const bottom = () => doc.page.height - MARGIN - 24;
  const ensure = (height: number) => {
    if (doc.y + height > bottom()) doc.addPage();
  };
  const costs = report.show_costs;

  // Header
  doc.image(readFileSync(LOGO), MARGIN, MARGIN, {
    height: 40,
  });
  doc
    .font('bold')
    .fontSize(18)
    .fillColor(INK)
    .text('Sales report', MARGIN, MARGIN, { width, align: 'right' });
  doc
    .font('regular')
    .fontSize(10)
    .fillColor(MUTED)
    .text(`${periodLabel(report)} · ${report.scope_label}`, {
      width,
      align: 'right',
    })
    .text(
      `Generated by ${meta.generatedBy} on ${manilaDateTime(meta.generatedAt)}`,
      { width, align: 'right' },
    );
  doc.y = Math.max(doc.y, MARGIN + 48) + 10;
  rule();

  // Headline cards
  section('Summary', comparisonLabel(report));
  const h = report.headline;
  const c = report.changes;
  // A missing change means the previous period had nothing to compare.
  const vs = (value: string | null, unit?: '%' | ' pts') =>
    value === null ? 'No earlier sales to compare' : change(value, unit);
  const cards: [string, string, string, boolean?][] = [
    ['Net sales', peso(h.net_sales), vs(c.net_sales)],
    ['Gross sales', peso(h.gross_sales), vs(c.gross_sales)],
    ['Sales', count(h.sales_count), vs(c.sales_count)],
    ['Average sale', peso(h.average_sale), vs(c.average_sale)],
    ...(costs
      ? ([
          ['Gross profit', peso(h.gross_profit), vs(c.gross_profit)],
          [
            'Food cost',
            `${peso(h.food_cost)} (${percent(h.food_cost_percent)})`,
            vs(c.food_cost_percent_points, ' pts'),
            true,
          ],
        ] as [string, string, string, boolean?][])
      : []),
    [
      'Voided sales',
      `${peso(h.void_amount)} (${h.void_count})`,
      c.void_amount === null ? '' : change(c.void_amount),
      true,
    ],
    ['Items sold', count(h.items_sold), ''],
  ];
  const cardWidth = (width - 3 * 8) / 4;
  cards.forEach(([label, value, delta, risingIsBad], index) => {
    const column = index % 4;
    if (column === 0) ensure(58);
    const x = MARGIN + column * (cardWidth + 8);
    const y = doc.y;
    doc.roundedRect(x, y, cardWidth, 52, 4).strokeColor(LINE).stroke();
    doc
      .font('regular')
      .fontSize(8)
      .fillColor(MUTED)
      .text(label, x + 8, y + 7, { width: cardWidth - 16 });
    doc
      .font('bold')
      .fontSize(11.5)
      .fillColor(INK)
      .text(value, x + 8, y + 19, {
        width: cardWidth - 16,
        lineBreak: false,
        ellipsis: true,
      });
    if (delta) {
      const rising = delta.startsWith('+');
      const falling = delta.startsWith('−');
      const color =
        rising || falling
          ? rising !== Boolean(risingIsBad)
            ? GOOD
            : BAD
          : MUTED;
      doc
        .font('regular')
        .fontSize(8)
        .fillColor(color)
        .text(delta, x + 8, y + 37, { width: cardWidth - 16 });
    }
    doc.y = column === 3 || index === cards.length - 1 ? y + 60 : y;
  });
  doc.x = MARGIN;
  if (
    costs &&
    h.cost_coverage_percent !== null &&
    Number(h.cost_coverage_percent) < 100
  ) {
    ensure(30);
    doc
      .font('regular')
      .fontSize(8.5)
      .fillColor('#92400E')
      .text(
        `Food cost covers ${h.cost_coverage_percent}% of net sales. Sales of products without a recipe or with uncosted stock add no food cost, so gross profit is overstated.`,
        MARGIN,
        doc.y,
        { width },
      );
    doc.moveDown(0.8);
  }

  // Cash and stock
  section('Cash and stock');
  const cashRows: string[][] = [
    ['Closed shifts', count(report.cash.closed_shifts)],
    ['Cash over/short (net)', peso(report.cash.cash_difference)],
    [
      'Short',
      `${peso(report.cash.short_amount)} in ${report.cash.short_shifts} shift(s)`,
    ],
    [
      'Over',
      `${peso(report.cash.over_amount)} in ${report.cash.over_shifts} shift(s)`,
    ],
    ['Approved daily reports', count(report.stock.approved_reports)],
    ...(costs
      ? [
          ['Waste value', peso(report.stock.waste_value)],
          ['Count variance value', peso(report.stock.variance_value)],
        ]
      : []),
  ];
  table(
    [
      { header: 'Item', width: width * 0.5 },
      { header: 'Value', width: width * 0.5, align: 'right' },
    ],
    cashRows,
  );

  // Breakdowns
  section('Branches');
  table(
    [
      { header: 'Branch', width: costs ? 150 : 205 },
      { header: 'Sales', width: 50, align: 'right' },
      { header: 'Net sales', width: costs ? 70 : 90, align: 'right' },
      { header: 'Avg sale', width: costs ? 60 : 80, align: 'right' },
      ...(costs
        ? [
            { header: 'Food cost', width: 60, align: 'right' as const },
            { header: 'Gross profit', width: 65, align: 'right' as const },
          ]
        : []),
      { header: 'Cash +/−', width: costs ? 60 : 90, align: 'right' },
    ],
    report.by_branch.map((row) => [
      row.branch_name,
      count(row.sales_count),
      peso(row.net_sales),
      peso(row.average_sale),
      ...(costs ? [peso(row.food_cost), peso(row.gross_profit)] : []),
      peso(row.cash_difference),
    ]),
  );
  section('Payment methods');
  table(
    [
      { header: 'Method', width: width - 230 },
      { header: 'Sales', width: 60, align: 'right' },
      { header: 'Amount', width: 100, align: 'right' },
      { header: 'Share', width: 70, align: 'right' },
    ],
    report.by_payment.map((row) => [
      row.name,
      count(row.sales_count),
      peso(row.amount),
      percent(row.share_percent),
    ]),
  );
  section('Dine-in and Takeout');
  table(
    [
      { header: 'Service', width: width - 230 },
      { header: 'Sales', width: 60, align: 'right' },
      { header: 'Amount', width: 100, align: 'right' },
      { header: 'Share', width: 70, align: 'right' },
    ],
    report.by_service.map((row) => [
      serviceLabel(row.service_type),
      count(row.sales_count),
      peso(row.amount),
      percent(row.share_percent),
    ]),
  );
  section('Categories');
  table(
    [
      { header: 'Category', width: width - (costs ? 300 : 230) },
      { header: 'Qty', width: 60, align: 'right' },
      { header: 'Net sales', width: 100, align: 'right' },
      ...(costs
        ? [{ header: 'Gross profit', width: 70, align: 'right' as const }]
        : []),
      { header: 'Share', width: 70, align: 'right' },
    ],
    report.by_category.map((row) => [
      row.name,
      count(row.quantity),
      peso(row.net_sales),
      ...(costs ? [peso(row.gross_profit)] : []),
      percent(row.share_percent),
    ]),
  );
  section('Top products');
  table(
    [
      { header: '#', width: 25 },
      { header: 'Product', width: width - (costs ? 255 : 185) },
      { header: 'Qty', width: 60, align: 'right' },
      { header: 'Net sales', width: 100, align: 'right' },
      ...(costs
        ? [{ header: 'Gross profit', width: 70, align: 'right' as const }]
        : []),
    ],
    report.top_products.map((row, index) => [
      String(index + 1),
      row.name,
      count(row.quantity),
      peso(row.net_sales),
      ...(costs ? [peso(row.gross_profit)] : []),
    ]),
  );
  if (report.daily.length) {
    section('Day by day');
    table(
      [
        { header: 'Business day', width: width - (costs ? 300 : 160) },
        { header: 'Sales', width: 60, align: 'right' },
        { header: 'Net sales', width: 100, align: 'right' },
        ...(costs
          ? [
              { header: 'Food cost', width: 70, align: 'right' as const },
              { header: 'Gross profit', width: 70, align: 'right' as const },
            ]
          : []),
      ],
      report.daily.map((row) => [
        new Intl.DateTimeFormat('en-PH', {
          timeZone: 'UTC',
          weekday: 'short',
        }).format(new Date(`${row.date}T00:00:00Z`)) +
          ', ' +
          shortDate(row.date),
        count(row.sales_count),
        peso(row.net_sales),
        ...(costs ? [peso(row.food_cost), peso(row.gross_profit)] : []),
      ]),
    );
  }

  // Footer on every page
  const pages = doc.bufferedPageRange();
  for (let index = 0; index < pages.count; index += 1) {
    doc.switchToPage(pages.start + index);
    const y = doc.page.height - MARGIN;
    doc.page.margins.bottom = 0;
    doc
      .font('regular')
      .fontSize(8)
      .fillColor(MUTED)
      .text(
        `Emma's Chicken House · Sales report · ${longDate(report.range.from)} – ${longDate(report.range.to)}`,
        MARGIN,
        y,
        { width, lineBreak: false },
      )
      .text(`Page ${index + 1} of ${pages.count}`, MARGIN, y, {
        width,
        align: 'right',
        lineBreak: false,
      });
  }
  doc.end();
  return done;

  function rule() {
    doc
      .moveTo(MARGIN, doc.y)
      .lineTo(MARGIN + width, doc.y)
      .strokeColor(LINE)
      .lineWidth(1)
      .stroke();
    doc.moveDown(0.8);
  }

  function section(title: string, note?: string) {
    ensure(60);
    doc.x = MARGIN;
    const y = doc.y + 4;
    doc.font('bold').fontSize(12).fillColor(INK).text(title, MARGIN, y);
    if (note)
      doc
        .font('regular')
        .fontSize(8.5)
        .fillColor(MUTED)
        .text(note, MARGIN, y + 3, { width, align: 'right' });
    doc.y = y + 20;
  }

  function table(columns: Column[], rows: string[][]) {
    const scale =
      width / columns.reduce((sum, column) => sum + column.width, 0);
    const widths = columns.map((column) => column.width * scale);
    const rowHeight = 18;
    const drawRow = (cells: string[], header: boolean) => {
      const y = doc.y;
      if (header) doc.rect(MARGIN, y, width, rowHeight).fill('#F3F4F6');
      let x = MARGIN;
      cells.forEach((cell, index) => {
        doc
          .font(header ? 'bold' : 'regular')
          .fontSize(8.5)
          .fillColor(header ? MUTED : INK)
          .text(cell, x + 6, y + 5, {
            width: widths[index] - 12,
            align: columns[index].align ?? 'left',
            lineBreak: false,
            ellipsis: true,
          });
        x += widths[index];
      });
      doc
        .moveTo(MARGIN, y + rowHeight)
        .lineTo(MARGIN + width, y + rowHeight)
        .strokeColor(LINE)
        .lineWidth(0.5)
        .stroke();
      doc.y = y + rowHeight;
    };
    ensure(rowHeight * 2);
    drawRow(
      columns.map((column) => column.header),
      true,
    );
    if (!rows.length) {
      doc
        .font('regular')
        .fontSize(8.5)
        .fillColor(MUTED)
        .text('No sales in this period.', MARGIN + 6, doc.y + 5);
      doc.y += rowHeight;
    }
    for (const row of rows) {
      if (doc.y + rowHeight > bottom()) {
        doc.addPage();
        drawRow(
          columns.map((column) => column.header),
          true,
        );
      }
      drawRow(row, false);
    }
    doc.x = MARGIN;
    doc.y += 14;
  }
}
